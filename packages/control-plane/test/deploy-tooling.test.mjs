// --- config repair ----------------------------------------------------------

// The deploy fills a stale config in from the example instead of refusing.
// Before this, a new var meant re-pasting CANARY_WRANGLER_TOML and
// PROD_WRANGLER_TOML by hand; it happened twice in one evening.
const REPAIR_EXAMPLE = [
  'name = "w"',
  "",
  "[vars]",
  'APP_URL = ""',
  'GIT_COMMIT_SHA = ""',
  'MICROVM_HOSTS = "[]"',
  "",
  "[assets]",
  'directory = "../webapp/dist"',
  'run_worker_first = [ "/version" ]',
  "",
  "[triggers]",
  'crons = [ "*/5 * * * *", "0 3 * * *" ]',
  "",
  "[observability]",
  "enabled = true",
  "",
].join("\n");

test("a var the example gained is filled in from the example, not demanded of the operator", () => {
  const config = [
    'name = "w"',
    "",
    "[vars]",
    'APP_URL = "https://deployed.example"',
    'MICROVM_HOSTS = "[]"',
    "",
    "[assets]",
    'directory = "../webapp/dist"',
    "",
    "[triggers]",
    'crons = [ "*/5 * * * *", "0 3 * * *" ]',
    "",
    "[observability]",
    "enabled = true",
    "",
  ].join("\n");
  const plan = configRepairPlan(REPAIR_EXAMPLE, config);
  assert.deepEqual(plan.unfillable, []);
  assert.deepEqual(plan.filled, [{ path: "vars.GIT_COMMIT_SHA", value: "" }]);
  assert.deepEqual(plan.patches, [{ vars: { GIT_COMMIT_SHA: "" } }]);
});

test("the repair never overwrites a value the deployment already set", () => {
  const plan = configRepairPlan(REPAIR_EXAMPLE, REPAIR_EXAMPLE.replace('APP_URL = ""', 'APP_URL = "https://deployed.example"'));
  assert.deepEqual(plan.filled, []);
  assert.deepEqual(plan.patches, []);
});

test("a whole missing table is filled in, values and all", () => {
  const config = ['name = "w"', "", "[vars]", 'APP_URL = ""', 'GIT_COMMIT_SHA = ""', 'MICROVM_HOSTS = "[]"', "", "[assets]", 'directory = "../webapp/dist"', "", "[triggers]", 'crons = [ "*/5 * * * *", "0 3 * * *" ]', ""].join("\n");
  const plan = configRepairPlan(REPAIR_EXAMPLE, config);
  assert.deepEqual(plan.filled, [{ path: "observability.enabled", value: true }]);
  assert.deepEqual(plan.patches, [{ observability: { enabled: true } }]);
});

test("the generated route list is never filled in: the deploy writes it", () => {
  const config = REPAIR_EXAMPLE.replace('run_worker_first = [ "/version" ]\n', "");
  const plan = configRepairPlan(REPAIR_EXAMPLE, config);
  assert.deepEqual(plan.filled, []);
  assert.deepEqual(plan.patches, []);
});

test("a missing cron is repaired as a union, so a deployment keeps its own", () => {
  const config = REPAIR_EXAMPLE.replace(
    'crons = [ "*/5 * * * *", "0 3 * * *" ]',
    'crons = [ "*/5 * * * *", "0 9 * * *" ]',
  );
  const plan = configRepairPlan(REPAIR_EXAMPLE, config);
  assert.deepEqual(plan.filled, [{ path: "triggers.crons[]", value: "0 3 * * *" }]);
  // Removed first, then written whole: wrangler patches an array element by
  // element and would otherwise leave the old tail in place.
  assert.deepEqual(plan.patches, [
    { triggers: { crons: undefined } },
    { triggers: { crons: ["*/5 * * * *", "0 9 * * *", "0 3 * * *"] } },
  ]);
});

test("a placeholder the operator alone can replace stops the deploy", () => {
  const example = ['name = "w"', "", "[vars]", 'ZONE = "<your zone id>"', ""].join("\n");
  const plan = configRepairPlan(example, 'name = "w"\n');
  assert.deepEqual(plan.filled, []);
  assert.equal(plan.unfillable.length, 1);
  assert.equal(plan.unfillable[0].path, "vars.ZONE");
  assert.match(plan.unfillable[0].reason, /placeholder/u);
});

test("the real example needs no repair against a config generated from it", () => {
  const example = readFileSync(path.join(packageDirectory, "wrangler.toml.example"), "utf8");
  const plan = configRepairPlan(example, example);
  assert.deepEqual(plan.filled, []);
  assert.deepEqual(plan.unfillable, []);
});

// --- worker-first route derivation ------------------------------------------

// One source of truth: core's own route registrations. Everything that used to
// hold a hand-written copy — wrangler.toml.example, the two deployment secrets,
// the managed worker, the vite dev proxy — asks the generator instead.

test("a segment with children gets a subtree entry, one without gets an exact entry", () => {
  const entries = runWorkerFirstEntries(["/me", "/members", "/members/:id", "/auth/google/start"]);
  assert.deepEqual(entries, ["/auth/*", "/me", "/members", "/members/*"]);
});

test("the root is an exact entry and never a prefix", () => {
  // "/*" would route every asset request — the SPA bundle included — through
  // the Worker, which is the failure this whole generator exists to prevent.
  const entries = runWorkerFirstEntries(["/", "/version"]);
  assert.deepEqual(entries, ["/", "/version"]);
  assert.equal(entries.includes("/*"), false);
  assert.equal(routingPlan(["/"]).root, true);
  assert.deepEqual(routingPlan(["/"]).segments, []);
});

test("the managed worker matches the root exactly, because it matches prefixes with startsWith", () => {
  assert.deepEqual(managedApiExactPaths(["/", "/version", "/members/:id"]), ["/", "/version"]);
  assert.deepEqual(managedApiPrefixes(["/", "/version", "/members/:id"]), ["/members/"]);
});

test("dev-proxy patterns are anchored, so a route never claims a name that starts like it", () => {
  const patterns = devProxyPatterns(["/", "/me", "/members/:id"]);
  // The root is absent on purpose: vite serves the SPA at "/" in dev.
  assert.deepEqual(patterns, ["^/me(?:$|[/?])", "^/members/"]);
  const matches = (url) => patterns.some((pattern) => new RegExp(pattern, "u").test(url));
  assert.equal(matches("/me"), true);
  assert.equal(matches("/me?x=1"), true);
  assert.equal(matches("/members/self"), true);
  assert.equal(matches("/menu"), false);
  assert.equal(matches("/members-directory"), false);
  assert.equal(matches("/index.html"), false);
  assert.equal(matches("/"), false);
});

test("a route registered with a computed path is named, not silently dropped", () => {
  const { paths, nonLiteral } = coreRoutePaths([
    { path: "core/a.ts", source: 'router.get("/ok", h);\nrouter.post(`/${dynamic}`, h);' },
  ]);
  assert.deepEqual(paths, ["/ok"]);
  assert.deepEqual(nonLiteral, [{ path: "core/a.ts", registrations: 2, literals: 1 }]);
});

test("router.all is scanned too, or /proxy leaves the list", () => {
  const { paths, nonLiteral } = coreRoutePaths([
    { path: "core/proxy.ts", source: 'router.all("/proxy/:leaseId/*", h);' },
  ]);
  assert.deepEqual(paths, ["/proxy/:leaseId/*"]);
  assert.deepEqual(nonLiteral, []);
});

test("the derived list claims a request to every route core registers today", () => {
  const entries = deriveRunWorkerFirst();
  const claims = (pathname) => entries.some((entry) => {
    const pattern = entry.split("*").map((literal) => literal.replaceAll(/[.+?^${}()|[\]\\]/gu, String.raw`\$&`)).join(".*");
    return new RegExp(`^${pattern}$`, "u").test(pathname);
  });
  for (const pathname of ["/version", "/me", "/sessions/switch-org", "/workspaces/abc/environment", "/proxy/lease/x", "/api/v1/health"]) {
    assert.equal(claims(pathname), true, pathname);
  }
  for (const pathname of ["/index.html", "/assets/index-abcd1234.js", "/members-directory", "/menu"]) {
    assert.equal(claims(pathname), false, pathname);
  }
});

