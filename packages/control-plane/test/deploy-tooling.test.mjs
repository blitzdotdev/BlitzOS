// --- routing list drift -----------------------------------------------------

// assets.run_worker_first is generated by the deploy now, so it is no longer
// compared. It used to be, because the key-path check passed a config that had
// the key and not the entry — /version reached wrangler.toml.example and
// neither deployment, and both passed. Comparing it today would fail the deploy
